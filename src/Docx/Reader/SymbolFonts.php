    public static function toUnicode(string $font, int $code): ?string
    {
        if ($code >= 0xF020 && $code <= 0xF0FF) {
            $code -= 0xF000;
        }

        foreach (self::TABLE as $name => $map) {
            if (strcasecmp($name, trim($font)) === 0) {
                return isset($map[$code]) ? mb_chr($map[$code], 'UTF-8') : null;
            }
        }

        return null;
    }

    public static function isSymbolFont(string $font): bool
    {
        foreach (array_keys(self::TABLE) as $name) {
            if (strcasecmp($name, trim($font)) === 0) {
                return true;
            }
        }

        return false;
    }
